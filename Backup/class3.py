class DiscountSystem:
    def __init__(self, original_price):
        self.original_price = original_price

    def apply_percentage_discount(self, percentage):
        """Applies a percentage discount (e.g., 10 for 10% off)"""
        discount_amount = self.original_price * (percentage / 100)
        final_price = self.original_price - discount_amount
        return max(0.0, final_price)

    def apply_flat_discount(self, amount):
        """Applies a flat-rate discount (e.g., $15 off)"""
        final_price = self.original_price - amount
        return max(0.0, final_price)

# Example usage:
cart = DiscountSystem(original_price=100.0)
print("Original Price: $100.0")
print("Price after 15% discount: $", cart.apply_percentage_discount(15))
print("Price after $20 flat discount: $", cart.apply_flat_discount(20))

